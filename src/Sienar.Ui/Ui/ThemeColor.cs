namespace Sienar.Ui;

/// <summary>
/// Sienar-supported theme colors
/// </summary>
public enum ThemeColor
{
	/// <summary>
	/// The primary theme color
	/// </summary>
	[HtmlValue("primary")]
	Primary,

	/// <summary>
	/// The text theme color
	/// </summary>
	[HtmlValue("text")]
	Text,

	/// <summary>
	/// The link theme color
	/// </summary>
	[HtmlValue("link")]
	Link,

	/// <summary>
	/// The info theme color
	/// </summary>
	[HtmlValue("info")]
	Info,

	/// <summary>
	/// The success theme color
	/// </summary>
	[HtmlValue("success")]
	Success,

	/// <summary>
	/// The warning theme color
	/// </summary>
	[HtmlValue("warning")]
	Warning,

	/// <summary>
	/// The danger theme color
	/// </summary>
	[HtmlValue("danger")]
	Danger
}
